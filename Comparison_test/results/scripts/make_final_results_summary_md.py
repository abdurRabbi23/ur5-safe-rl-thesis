#!/usr/bin/env python3
"""Human-readable numbers table for Chapter 4, generated from final_results_summary.json.
This is the source-of-truth numbers doc for the 5-seed/3-arm scope -- the successor to the
superseded MATRIX_V2_PARTIAL_3ARM.md. Every number in the Chapter 4 rewrite should trace here.
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS = os.path.dirname(HERE)
with open(os.path.join(RESULTS, "final_results_summary.json")) as f:
    D = json.load(f)

ARMS = ["ctrl", "cppo", "cppo15"]
LABEL = {"ctrl": "PPO (baseline)", "cppo": "cPPO (d=25)", "cppo15": "cPPO (d=15)"}
SEEDS = D["scope"]["seeds"]

lines = []
lines.append("# Final results summary -- 5 seeds x 3 arms (locked scope, 2026-08-02)")
lines.append("")
lines.append(f"Source: `Comparison_test/final_results/`. Seeds: {SEEDS}. Arms: ctrl (\"PPO (baseline)\"), cppo (d=25), cppo15 (d=15).")
lines.append("Generated by `build_final_results_data.py` + `make_final_results_summary_md.py`. Do not hand-edit -- regenerate.")
lines.append("")
lines.append("## Training (tail mean, last 10% of 1500 iterations, n=5 seeds)")
lines.append("")
lines.append("| Metric | " + " | ".join(LABEL[a] for a in ARMS) + " |")
lines.append("|---|" + "---|" * len(ARMS))
for metric, label in [("mean_reward", "Mean reward"), ("mean_episode_cost", "Mean episode cost"),
                        ("reaching_object", "Reaching-object reward"), ("lifting_object", "Lifting-object reward"),
                        ("cost_lambda", "Lagrange multiplier (final tail)"),
                        ("manip_min", "Mean episode-min manipulability")]:
    row = [label]
    for a in ARMS:
        t = D["training"][a][metric]
        row.append(f"{t['tail_mean']:.4f} ± {t['tail_std']:.4f}")
    lines.append("| " + " | ".join(row) + " |")
lines.append("")
lines.append("### Per-seed mean_episode_cost tail mean (training)")
lines.append("")
lines.append("| Seed | " + " | ".join(LABEL[a] for a in ARMS) + " |")
lines.append("|---|" + "---|" * len(ARMS))
for s in SEEDS:
    row = [str(s)]
    for a in ARMS:
        row.append(f"{D['training'][a]['mean_episode_cost']['per_seed_tail'][str(s)]:.2f}")
    lines.append("| " + " | ".join(row) + " |")
lines.append("")
lines.append("## Evaluation (frozen policy, pooled over 5 seeds x 3 eval seeds = 15,000 episodes/arm)")
lines.append("")
ev_rows = [
    ("lift_rel_pct", "Lift success (headline, %)"),
    ("goal_reach_1cm_pct", "Goal-reach < 1 cm (%)"),
    ("goal_reach_2cm_pct", "Goal-reach < 2 cm (%)"),
    ("goal_reach_5cm_pct", "Goal-reach < 5 cm (%)"),
    ("goal_dist_mean", "Goal distance mean (m)"),
    ("goal_dist_median", "Goal distance median (m)"),
    ("goal_dist_p90", "Goal distance p90 (m)"),
    ("goal_dist_max", "Goal distance max (m)"),
    ("sing_touched_pct", "Singularity touched (% episodes)"),
    ("joint_touched_pct", "Joint-limit touched (% episodes)"),
    ("coll_touched_pct", "Collision touched (% episodes)"),
    ("true_singularity_pct", "True singularity crossing, w<1e-4 (%)"),
    ("true_singularity_n", "True singularity crossing (n episodes)"),
    ("mean_episode_min_manip", "Mean episode-min manipulability"),
    ("worst_episode_min_manip", "Worst episode-min manipulability"),
    ("cost_mean", "Episodic safety cost, mean"),
    ("cost_median", "Episodic safety cost, median"),
    ("cost_p90", "Episodic safety cost, p90"),
    ("cost_max", "Episodic safety cost, max"),
    ("cost_std_across_episodes", "Episodic safety cost, std (episodes)"),
]
lines.append("| Metric | " + " | ".join(LABEL[a] for a in ARMS) + " |")
lines.append("|---|" + "---|" * len(ARMS))
for key, label in ev_rows:
    row = [label]
    for a in ARMS:
        v = D["evaluation"][a][key]
        row.append(f"{v:.4f}" if isinstance(v, float) else str(v))
    lines.append("| " + " | ".join(row) + " |")
lines.append("")
lines.append("### Per-seed episodic cost mean (evaluation, 3000 episodes/seed)")
lines.append("")
lines.append("| Seed | " + " | ".join(LABEL[a] for a in ARMS) + " |")
lines.append("|---|" + "---|" * len(ARMS))
for s in SEEDS:
    row = [str(s)]
    for a in ARMS:
        row.append(f"{D['evaluation'][a]['per_seed_cost_mean'][str(s)]:.2f}")
    lines.append("| " + " | ".join(row) + " |")

out_path = os.path.join(RESULTS, "FINAL_RESULTS_SUMMARY.md")
with open(out_path, "w") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", out_path)
